// Brand asset generator for HTML Runner.
// Run from the repo root:  node scripts/brand/build.mjs
//
// Produces:
//   public/favicon.svg            theme-aware mark (prefers-color-scheme inside the SVG)
//   public/favicon.png            32x32
//   public/apple-touch-icon.png   180x180, full bleed (iOS rounds it)
//   public/icon-192.png, public/icon-512.png   full bleed, mark inside the maskable safe zone
//   public/og.png                 1200x630 social card
//   scripts/brand/og.svg, scripts/brand/mark.svg   the vector sources of the above
//   src/components/brand/logo-paths.ts   path data consumed by Logo.astro
//
// All text is converted to outlines from the self-hosted Archivo / JetBrains Mono variable fonts,
// so the rasters do not depend on fonts installed on the machine.
import sharp from 'sharp';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { textPath } from './text-to-path.mjs';

const root = process.cwd();
const out = (p) => join(root, p);
const write = (p, data) => {
  mkdirSync(dirname(out(p)), { recursive: true });
  writeFileSync(out(p), data);
};

// Tokens (mirrors src/styles/global.css).
const T = {
  light: { paper: '#f4f1ea', ink: '#16150f', ink2: '#45433a', muted: '#6d6a5f', line: '#d9d4c6', track: '#d93d22', onTrack: '#fffaf2' },
  dark: { paper: '#121210', ink: '#efece3', track: '#ff5a3c', onTrack: '#1a0d09' },
  lanes: { html: '#d93d22', css: '#1d5fbf', js: '#9a6a00' },
};

/*
 * The mark: a "run" (play) triangle sliced into three lanes, one per language,
 * on a tartan-track tile. Designed on a 32-unit grid so the lane gaps land on whole pixels at 16px.
 * The triangle sits 1 unit right of centre to look optically centred.
 */
export const MARK_LANES = [
  '10,6 19.52,11.6 10,11.6',
  '10,13.6 22.92,13.6 27,16 22.92,18.4 10,18.4',
  '10,20.4 19.52,20.4 10,26',
];
const MARK_RADIUS = 7;

const lanesSvg = (fill, transform = '') =>
  `<g fill="${fill}"${transform ? ` transform="${transform}"` : ''}>${MARK_LANES.map((p) => `<polygon points="${p}"/>`).join('')}</g>`;

function markSvg({ size = 32, radius = MARK_RADIUS, bleed = false, scale = 1 } = {}) {
  // scale < 1 shrinks the lanes around the tile centre (used for maskable icons).
  const t = scale === 1 ? '' : `translate(${16 - 16 * scale} ${16 - 16 * scale}) scale(${scale})`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 32 32">
  <rect width="32" height="32" rx="${bleed ? 0 : radius}" fill="${T.light.track}"/>
  ${lanesSvg(T.light.onTrack, t)}
</svg>`;
}

// Theme-aware favicon: the dark variant uses the brighter dark-theme track with dark lanes.
const faviconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <style>
    .tile { fill: ${T.light.track}; }
    .lane { fill: ${T.light.onTrack}; }
    @media (prefers-color-scheme: dark) {
      .tile { fill: ${T.dark.track}; }
      .lane { fill: ${T.dark.onTrack}; }
    }
  </style>
  <rect class="tile" width="32" height="32" rx="${MARK_RADIUS}"/>
  ${MARK_LANES.map((p) => `<polygon class="lane" points="${p}"/>`).join('\n  ')}
</svg>
`;

// Wordmark: "HTML Runner" in the display voice (Archivo 800, width 125).
const WORD_SIZE = 21;
const WORD_X = 42;
const WORD_BASELINE = 23.4;
const word = textPath('HTML Runner', {
  size: WORD_SIZE,
  x: WORD_X,
  y: WORD_BASELINE,
  axes: { wght: 800, wdth: 125 },
  tracking: -0.02,
});
const wordWidth = Math.ceil(WORD_X + word.width + 1);

const logoTs = `// Generated by scripts/brand/build.mjs. Do not edit by hand.
/** Lane polygons of the mark, on a 32x32 grid. */
export const MARK_LANES = ${JSON.stringify(MARK_LANES)} as const;
export const MARK_RADIUS = ${MARK_RADIUS};
/** "HTML Runner" outlined in Archivo 800 / width 125, positioned to sit right of the 32-unit mark. */
export const WORDMARK_PATH = ${JSON.stringify(word.d)};
/** Full lockup viewBox width (height is 32). */
export const LOCKUP_WIDTH = ${wordWidth};
`;

// ---------- OG card ----------
function ogSvg() {
  const W = 1200;
  const H = 630;
  const c = T.light;
  const parts = [];
  parts.push(`<rect width="${W}" height="${H}" fill="${c.paper}"/>`);

  // Header row: mark + URL.
  parts.push(`<g transform="translate(80 64) scale(2)"><rect width="32" height="32" rx="${MARK_RADIUS}" fill="${c.track}"/>${lanesSvg(c.onTrack)}</g>`);
  const url = textPath('htmlrunner.h190k.com', { family: 'mono', size: 22, x: W - 80, y: 104, axes: { wght: 500 }, anchor: 'end' });
  parts.push(`<path d="${url.d}" fill="${c.muted}"/>`);

  // Name and line.
  const name = textPath('HTML Runner', { size: 132, x: 74, y: 292, axes: { wght: 800, wdth: 125 }, tracking: -0.035 });
  parts.push(`<path d="${name.d}" fill="${c.ink}"/>`);
  const line = textPath('Write HTML, CSS and JavaScript. Watch it run.', {
    size: 38,
    x: 80,
    y: 366,
    axes: { wght: 450, wdth: 100 },
    tracking: -0.005,
  });
  parts.push(`<path d="${line.d}" fill="${c.ink2}"/>`);

  // The track: three lanes along the bottom edge, painted like a real start.
  const top = 438;
  const laneH = 64;
  const lineW = 3;
  parts.push(`<rect x="0" y="${top}" width="${W}" height="${H - top}" fill="${c.track}"/>`);
  for (let i = 0; i <= 3; i++) {
    const y = top + i * laneH;
    if (i > 0) parts.push(`<rect x="0" y="${y - lineW / 2}" width="${W}" height="${lineW}" fill="${c.onTrack}"/>`);
  }
  // Start line.
  parts.push(`<rect x="232" y="${top}" width="6" height="${H - top}" fill="${c.onTrack}"/>`);

  const lanes = [
    ['1', 'HTML', '<h1>Hello, Runner.</h1>'],
    ['2', 'CSS', 'h1 { letter-spacing: -0.03em; }'],
    ['3', 'JS', "console.log('split', time);"],
  ];
  lanes.forEach(([n, lang, code], i) => {
    const mid = top + i * laneH + laneH / 2;
    const num = textPath(n, { size: 42, x: 92, y: mid + 15, axes: { wght: 800, wdth: 125 } });
    parts.push(`<path d="${num.d}" fill="${c.onTrack}"/>`);
    const lab = textPath(lang, { family: 'mono', size: 20, x: 136, y: mid + 7, axes: { wght: 600 }, tracking: 0.08 });
    parts.push(`<path d="${lab.d}" fill="${c.onTrack}"/>`);
    const code1 = textPath(code, { family: 'mono', size: 24, x: 270, y: mid + 8, axes: { wght: 400 } });
    parts.push(`<path d="${code1.d}" fill="${c.onTrack}" fill-opacity="0.82"/>`);
  });

  // Stopwatch readout in the last lane, right aligned.
  const ms = textPath('12 ms', { family: 'mono', size: 30, x: W - 80, y: top + 2 * laneH + laneH / 2 + 10, axes: { wght: 600 }, anchor: 'end' });
  const tick = W - 80 - ms.width - 22;
  const cy = top + 2 * laneH + laneH / 2;
  parts.push(`<circle cx="${tick}" cy="${cy}" r="7" fill="${c.onTrack}"/>`);
  parts.push(`<path d="${ms.d}" fill="${c.onTrack}"/>`);

  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">\n${parts.join('\n')}\n</svg>\n`;
}

async function png(svg, file, size) {
  const img = sharp(Buffer.from(svg), { density: 72 * Math.max(1, size ? size / 32 : 1) });
  await (size ? img.resize(size, size) : img).png({ compressionLevel: 9 }).toFile(out(file));
}

write('public/favicon.svg', faviconSvg);
write('scripts/brand/mark.svg', markSvg({ size: 512 }));
write('src/components/brand/logo-paths.ts', logoTs);
const og = ogSvg();
write('scripts/brand/og.svg', og);

await png(markSvg({ size: 32 }), 'public/favicon.png', 32);
await png(markSvg({ size: 180, bleed: true, scale: 0.86 }), 'public/apple-touch-icon.png', 180);
await png(markSvg({ size: 192, bleed: true, scale: 0.8 }), 'public/icon-192.png', 192);
await png(markSvg({ size: 512, bleed: true, scale: 0.8 }), 'public/icon-512.png', 512);
await sharp(Buffer.from(og)).png({ compressionLevel: 9 }).toFile(out('public/og.png'));

console.log('brand assets written');
